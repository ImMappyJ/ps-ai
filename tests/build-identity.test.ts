import test from 'node:test';import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';import path from 'node:path';
import fs from 'node:fs/promises';

test('build identification records source revision and dirty/unavailable state without paths or timestamps',async()=>{
  const entry=pathToFileURL(path.resolve('scripts/build-identity.mjs')).href;
  const helper=await import(entry).catch(()=>undefined);assert.ok(helper,'build identity must be generated by build-time Node code');
  const {version}=JSON.parse(await fs.readFile('package.json','utf8'));
  const git=(status:string)=>(args:string[])=>args[0]==='rev-parse'?'0123456789abcdef0123456789abcdef01234567\n':status;
  assert.equal(helper.readBuildIdentity(process.cwd(),git('')),`PS-AI ${version} · 01234567`);
  for(const status of [' M src/app/panel.ts\n','?? src/new-feature.ts\n'])assert.equal(helper.readBuildIdentity(process.cwd(),git(status)),`PS-AI ${version} · 01234567-dirty`);
  assert.equal(helper.readBuildIdentity(process.cwd(),()=>{throw Error('private path must never appear');}),`PS-AI ${version} · unknown-dirty`);
});
